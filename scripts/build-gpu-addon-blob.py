#!/usr/bin/env python3
"""Build the GPU addon blob embedded in the uke kernel.

The blob is the owner-built NativeAdrenoMetal bundle, its publish/client
markers and the probe daemon (build/adreno-metal-plugin in the UniXNU core
checkout), packed as [uncompressed header][zlib-compressed entries] and
assembled into a Mach-O object by the kernel archive step. The kernel stages
it into the Data volume on the first boot after the Data mount, before the
addon bindfs mount, so the same files the macOS image tools write into a
packed Data seed are produced on the device.

  build-gpu-addon-blob.py [--plugin-dir DIR] [--output-dir DIR] [--clients NAMES]

The generated GpuAddonBlob.S embeds the blob with .incbin and exports
_native_gpu_addon_blob, _native_gpu_addon_blob_end, _native_gpu_addon_blob_size
and _native_gpu_addon_blob_cookie."""
import argparse
import hashlib
import json
import struct
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_PLUGIN = Path('/home/allenwdk/UniXNU/UniXNU/build/adreno-metal-plugin')
MAGIC = b'NGPUADD2'
HEADER = struct.Struct('<8sIIQQ')   # magic, version, count, raw bytes, cookie
VERSION = 2


def fnv1a(data):
    value = 0x811c9dc5
    for byte in data:
        value = ((value ^ byte) * 0x01000193) & 0xffffffff
    return value


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--plugin-dir', type=Path, default=DEFAULT_PLUGIN)
    parser.add_argument('--output-dir', type=Path, default=ROOT / 'build/uke-gpu-addon')
    parser.add_argument('--clients', default='iconservicesagent,PosterBoard,WidgetRenderer_Default,CollectionsPoster,AegirPoster,KaleidoscopePoster')
    parser.add_argument('--no-publish', action='store_true',
                        help='probe image: omit the .publish marker so the plugin runs its shared user test and returns nil (software rendering kept)')
    args = parser.parse_args()
    plugin = args.plugin_dir.resolve()
    bundle = plugin / 'NativeAdrenoMetal.bundle'
    executable = bundle / 'NativeAdrenoMetal'
    turnip = bundle / 'libvulkan_freedreno.dylib'
    info = bundle / 'Info.plist'
    daemon = plugin / 'adrenoprobed'
    daemon_plist = plugin / 'org.blu-sharky.adrenoprobed.plist'
    for path in (executable, turnip, info, daemon, daemon_plist):
        if not path.is_file():
            sys.exit('missing plugin input: ' + str(path))
    entries = [
        ('addons/NativeAdrenoMetal.bundle/NativeAdrenoMetal', 0o755, executable.read_bytes()),
        ('addons/NativeAdrenoMetal.bundle/libvulkan_freedreno.dylib', 0o755, turnip.read_bytes()),
        ('addons/NativeAdrenoMetal.bundle/Info.plist', 0o644, info.read_bytes()),
        ('addons/NativeAdrenoMetal.clients', 0o644, (args.clients.replace(',', '\n') + '\n').encode()),
        ('bin/adrenoprobed', 0o755, daemon.read_bytes()),
        ('daemons/org.blu-sharky.adrenoprobed.plist', 0o644, daemon_plist.read_bytes()),
    ]
    if not args.no_publish:
        entries.insert(3, ('addons/NativeAdrenoMetal.publish', 0o644, b'1\n'))
    body = bytearray()
    paths = []
    for path, mode, data in entries:
        name = path.encode()
        body += struct.pack('<IIQ', len(name), mode, len(data)) + name + data
        paths.append({'path': path, 'mode': mode, 'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()})
    compressed = zlib.compress(bytes(body), 9)
    cookie = fnv1a(bytes(body))
    blob = HEADER.pack(MAGIC, VERSION, len(entries), len(body), cookie) + compressed
    out = args.output_dir.resolve()
    out.mkdir(parents=True, exist_ok=True)
    (out / 'gpu-addon.z').write_bytes(blob)
    (out / 'GpuAddonBlob.S').write_text(
        '/* Generated by scripts/build-gpu-addon-blob.py; do not edit. */\n'
        '.section __DATA,__const\n'
        '.globl _native_gpu_addon_blob_cookie\n'
        '.p2align 3\n'
        '_native_gpu_addon_blob_cookie:\n'
        '.long %d\n'
        '.globl _native_gpu_addon_blob_size\n'
        '.p2align 3\n'
        '_native_gpu_addon_blob_size:\n'
        '.quad %d\n'
        '.globl _native_gpu_addon_blob_raw_size\n'
        '.p2align 3\n'
        '_native_gpu_addon_blob_raw_size:\n'
        '.quad %d\n'
        '.globl _native_gpu_addon_blob\n'
        '.p2align 12\n'
        '_native_gpu_addon_blob:\n'
        '.incbin "%s"\n'
        '.globl _native_gpu_addon_blob_end\n'
        '_native_gpu_addon_blob_end:\n' % (cookie, len(blob), len(body), out / 'gpu-addon.z'))
    report = {
        'blob': str(out / 'gpu-addon.z'), 'bytes': len(blob), 'compressed_bytes': len(compressed),
        'raw_bytes': len(body), 'cookie': cookie, 'entries': paths,
        'blob_sha256': hashlib.sha256(blob).hexdigest(),
    }
    (out / 'gpu-addon.json').write_text(json.dumps(report, indent=2) + '\n')
    print('PASS: GPU addon blob %d bytes (%d raw, cookie %08x); %d entries%s' % (
        len(blob), len(body), cookie, len(entries), ' (probe, no publish marker)' if args.no_publish else ''))


if __name__ == '__main__':
    main()
